def infer_unite_repli(metrique):
    """Unité déduite du nom de métrique quand le couple est absent de UNITE_MAP."""
    m = str(metrique).lower()
    if 'pourcentage' in m or m.startswith('%'):
        return '%'
    if 'longueur' in m or m.startswith('lin') or m.startswith('long'):
        return 'km'
    if m.startswith('nbr') or m.startswith('nb_') or m.startswith('nbre') or m.startswith('nombre'):
        return 'nb'
    if 'age' in m:
        return 'ans'
    if m.startswith('vp') or m.startswith('val'):
        return '€'
    return ''


def get_indicateur_libelle(indicateur):
    return INDICATEUR_LIBELLES.get(indicateur, indicateur)


def get_metrique_libelle(indicateur, metrique):
    return METRIQUE_LIBELLES.get((indicateur, metrique), metrique)


def get_unite(indicateur, metrique):
    if (indicateur, metrique) in UNITE_MAP:
        return UNITE_MAP[(indicateur, metrique)]
    return infer_unite_repli(metrique)
